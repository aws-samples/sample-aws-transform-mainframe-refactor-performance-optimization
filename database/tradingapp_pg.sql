-- ---------------------------------------------------------------------------
-- Application database role (least privilege)
--
-- The application needs only DML on the tables above. Schema changes and test
-- data loading stay with an administrative login, so this role deliberately has
-- no DDL and no TRUNCATE privilege.
--
-- Run this section as an administrative user, after the tables exist. Granting
-- "ON ALL TABLES" only affects tables that already exist, so it must come last.
--
-- No password is set here. Local loopback connections are expected to be
-- trusted in pg_hba.conf; see SECURITY.md. If your instance requires a
-- password, set one locally with \password tradingapp_app and never commit it.
-- ---------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'tradingapp_app') THEN
    CREATE ROLE tradingapp_app LOGIN;
  END IF;
END
$$;

GRANT CONNECT ON DATABASE tradingapp TO tradingapp_app;
